"""Recreate frozen C stage vectors using the independent Python oracle."""
import argparse
from pathlib import Path
from oracle import MASK, round_constants, stages, trace

ROOT = Path(__file__).resolve().parents[1]


def words(values):
    return '{' + ', '.join('UINT64_C(0x%016x)' % v for v in values) + '}'


def stage_header():
    rc = round_constants()
    inputs = [[0] * 6, [MASK] * 6,
              [int.from_bytes(bytes(range(8 * i, 8 * i + 8)), 'little') for i in range(6)],
              [1 << 63, 1, MASK, 0, 0xaaaaaaaaaaaaaaaa, 0x5555555555555555]]
    rows = []
    for r in (0, 7, 15):
        for source in inputs:
            fields = (source,) + stages(source, r, rc)
            rows.append('    {%du,\n        %s},' % (r, ',\n        '.join(map(words, fields))))
    return ('/* Generated by tests/vectors.py --write; compare, do not hand-edit. */\n'
            '#ifndef CROSSWEAVE_STAGE_VECTORS_H\n#define CROSSWEAVE_STAGE_VECTORS_H\n'
            '#include <stdint.h>\n'
            'static const struct {\n    unsigned round;\n'
            '    uint64_t input[6], even[6], odd[6], added[6], shuffled[6];\n'
            '} stage_vectors[] = {\n' + '\n'.join(rows) + '\n};\n#endif\n')


def permutation_header():
    rows = []
    for source in (bytes(48), b'\xff' * 48, bytes(range(48))):
        history = trace(source)
        lane = lambda b: [int.from_bytes(b[i:i + 8], 'little') for i in range(0, 48, 8)]
        rows.append('    {%s, {\n        %s}},' %
                    (words(lane(source)), ',\n        '.join(words(lane(x)) for x in history)))
    return ('/* Generated by tests/vectors.py --write from the independent oracle. */\n'
            '#ifndef CROSSWEAVE_PERMUTATION_VECTORS_H\n#define CROSSWEAVE_PERMUTATION_VECTORS_H\n'
            '#include <stdint.h>\nstatic const struct {\n'
            '    uint64_t input[6], after[16][6];\n'
            '} permutation_vectors[] = {\n' + '\n'.join(rows) + '\n};\n#endif\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for name, expected in (('stage_vectors.h', stage_header()),
                           ('permutation_vectors.h', permutation_header())):
        path = ROOT / 'tests' / name
        if args.write:
            path.write_text(expected)
        elif path.read_text() != expected:
            raise SystemExit(name + ' differs; investigate the specification and core')
    print('Frozen half-round and full-round vectors match independent oracle')
