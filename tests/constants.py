"""Validate SHAKE independently, then check the frozen public C constants."""
import hashlib
import sys
import unittest
from pathlib import Path
from oracle import shake256, round_constants

ROOT = Path(__file__).resolve().parents[1]
# NIST SHAKE256_Msg0.pdf, final output, first 64 bytes.
# https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Standards-and-Guidelines/documents/examples/SHAKE256_Msg0.pdf
EMPTY = bytes.fromhex(
    '46b9dd2b0ba88d13233b3feb743eeb243fcd52ea62b81b82b50c27646ed5762f'
    'd75dc4ddd8c0f200cb05019d67b592f6fc821c49479ab48640292eacb3b7c4be')


def header():
    rows = '\n'.join('    {UINT64_C(0x%016x), UINT64_C(0x%016x)},' % tuple(row)
                     for row in round_constants())
    return ('/* Generated by tests/constants.py --write; domains in docs/spec_ko.md. */\n'
            '#ifndef CROSSWEAVE_CONSTANTS_H\n#define CROSSWEAVE_CONSTANTS_H\n\n'
            '#include <stdint.h>\n\nstatic const uint64_t cw_rc[16][2] = {\n' +
            rows + '\n};\n\n#endif\n')


class Constants(unittest.TestCase):
    def test_nist_empty(self):
        self.assertEqual(shake256(b'', 64), EMPTY)
        self.assertEqual(hashlib.shake_256(b'').digest(64), EMPTY)

    def test_independent_rate_boundaries(self):
        for n in (0, 1, 135, 136, 137, 271, 272, 273):
            data = bytes(i % 256 for i in range(n))
            for size in (0, 8, 16, 64, 137, 272):
                self.assertEqual(shake256(data, size), hashlib.shake_256(data).digest(size))

    def test_domains_and_frozen_table(self):
        for r, row in enumerate(round_constants()):
            for j, value in zip((0, 3), row):
                data = f'cw-p384/round-{r}/lane-{j}'.encode('ascii')
                self.assertEqual(value.to_bytes(8, 'little'), hashlib.shake_256(data).digest(8))
        self.assertEqual(shake256(b'CrossWeave/IV', 16),
                         hashlib.shake_256(b'CrossWeave/IV').digest(16))
        self.assertEqual((ROOT / 'src/crossweave_constants.h').read_text(), header())


if __name__ == '__main__':
    if sys.argv[1:] == ['--write']:
        assert shake256(b'', 64) == EMPTY
        (ROOT / 'src/crossweave_constants.h').write_text(header())
    else:
        unittest.main()
